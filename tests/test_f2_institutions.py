from __future__ import annotations

import pytest

from tools.f2.institutions import group, rows, university


@pytest.mark.parametrize("raw, expected", [
    ("มทร.ศรีวิชัย", "มหาวิทยาลัยเทคโนโลยีราชมงคลศรีวิชัย"),
    ("มหาวิทยาลัยเทคโนโลยีราชมงคลศรีวิชัย วิทยาเขตตรัง", "มหาวิทยาลัยเทคโนโลยีราชมงคลศรีวิชัย"),
    ("มทร.ล้านนา เชียงราย", "มหาวิทยาลัยเทคโนโลยีราชมงคลล้านนา"),
    ("มรภ เลย", "มหาวิทยาลัยราชภัฏเลย"),
    ("มหาวิทยาลัยราชภัฎเลย", "มหาวิทยาลัยราชภัฏเลย"),
    ("ม.ราชภัฏนครศรีธรรมราช", "มหาวิทยาลัยราชภัฏนครศรีธรรมราช"),
    ("มหาวิทยาลัยราชภัฏวไลยอลงกรณ์ ในพระบรมราชูปถัมภ์", "มหาวิทยาลัยราชภัฏวไลยอลงกรณ์"),
    ("มรภ.วไลยอลงกรณ์ฯ", "มหาวิทยาลัยราชภัฏวไลยอลงกรณ์"),
    ("มหาวิทยาลัยราชภัฏกำแพงเพชร แม่สอด", "มหาวิทยาลัยราชภัฏกำแพงเพชร"),
    ("มหาวิทยาลัยราชภัฏอุดรธานี ศูนย์การศึกษาบึงกาฬ", "มหาวิทยาลัยราชภัฏอุดรธานี"),
    ("มหาวิทยาลัยเทคโนโลยีพระจอมเกล้าธนบุรี วิทยาเขต ราชบุรี", "มหาวิทยาลัยเทคโนโลยีพระจอมเกล้าธนบุรี"),
    ("ม.แม่โจ้", "มหาวิทยาลัยแม่โจ้"),
    ("ม.ฟ.น.", "มหาวิทยาลัยฟาฏอนี"),
    ("สถาบันเทคโนโลยีพระจอมเกล้าเจ้าคุณหทารลาดกระบัง", "สถาบันเทคโนโลยีพระจอมเกล้าเจ้าคุณทหารลาดกระบัง"),
    ("กรมการข้าว", "กรมการข้าว"),
    ("  ", None),
])
def test_university_folds_spellings(raw, expected):
    assert university(raw) == expected


def test_groups_and_rows():
    assert [group(university(n) or "") for n in ("มรภ.สงขลา", "มทร.อีสาน", "ม.เชียงใหม่", "จุฬาลงกรณ์มหาวิทยาลัย",
                                                 "มูลนิธิเพื่อการพัฒนาที่ยั่งยืน ภาคเหนือ", "วิทยาลัยชุมชน")] \
        == ["rajabhat", "rajamangala", "university", "university", "other", "other"]
    assert rows(["มทร.อีสาน", None, "", "มทร.อีสาน"]) == [
        {"raw": "มทร.อีสาน", "university": "มหาวิทยาลัยเทคโนโลยีราชมงคลอีสาน", "university_group": "rajamangala"}]
